put(3,1,22,'操作手')
for c in (2,22):
    put(3,7,c,'IMU');put(3,12,c,'归中结果');put(3,17,c,'状态')
put(3,27,1,'KEY0归中当前手 KEY2切换操作手')
put(3,28,1,'KEY1+KEY2返回演奏/教学')
chars=[' ']+sorted(set(''.join(sum(pages,[]))+''.join(labels.values())+'0123456789%/-')-{' '})
assert len(chars)<256
glyphs=[]
for ch in chars:
    im=Image.new('L',(16,16));d=ImageDraw.Draw(im);b=d.textbbox((0,0),ch,font=font)
    d.text(((16-(b[2]-b[0]))//2-b[0],(16-(b[3]-b[1]))//2-b[1]),ch,font=font,fill=255)
    glyphs += [sum(1<<(15-x) for x in range(16) if im.getpixel((x,y))>=112) for y in range(16)]
rom=[chars.index(c) for page in pages for line in page for c in line]
ids={k:i for i,k in enumerate(labels)}
for text in labels.values():
    assert len(text)<=20
    rom += [chars.index(c) for c in text.ljust(20)]
assert len(rom)<=8192
(ROOT/'rtl/ui23_text.hex').write_text(''.join(f'{v:03x}\n' for v in rom+[0]*(8192-len(rom))),encoding='ascii')
(ROOT/'rtl/ui23_font.hex').write_text(''.join(f'{v:04x}\n' for v in glyphs+[0]*(4096-len(glyphs))),encoding='ascii')
vh='// Generated by generate_ui23.py\n'+''.join(f'localparam [6:0] L_{k}=7\'d{i};\n' for k,i in ids.items())
vh+='function [8:0] digit_glyph;input [3:0] d;begin case(d)\n'+''.join(f'{i}:digit_glyph=9\'d{chars.index(str(i))};\n' for i in range(10))+"default:digit_glyph=0;endcase end endfunction\n"
vh+=f"localparam [8:0] GLYPH_PERCENT=9'd{chars.index('%')};\n"
(ROOT/'rtl/ui23_labels.vh').write_text(vh,encoding='ascii')
profiles=[['DO','RE','MI','FA','SOL','LA','SI'],['DO','RE','MI','SOL','LA'],['DO','DOS','RE','RES','MI','FA','FAS','SOL','SOLS','LA','LAS','SI']]
note='// ASCII note labels use 8px pitch with full 16px glyph height.\n'
for p,ns in enumerate(profiles):
    note+=f'if(perform && label_profile==2\'d{p})begin\n'
    for i,n in enumerate(ns):
        a=math.radians(-90+(i+.5)*180/len(ns));text=labels[n]
        cx=round(140+108*math.sin(a));cy=round(140-108*math.cos(a))
        xx=cx-len(text)*4;yy=184+cy-8
        note+=f" if(local_label_x>={xx} && local_label_x<{xx+len(text)*8} && y>={yy} && y<{yy+16})begin address=13'd{4800+ids[n]*20}+(local_label_x-{xx})/8;small_text=1;small_col=(local_label_x-{xx})%8+4;small_row=y-{yy};end\n"
    note+='end\n'
(ROOT/'rtl/ui23_note_labels.vh').write_text(note,encoding='ascii')
# A tiny 32x40 hand outline. The signal drives a monochrome ROM mask.
im=Image.new('1',(32,40));d=ImageDraw.Draw(im)
d.line([(8,23),(8,10),(11,8),(14,10),(14,23)],fill=1,width=2)
d.line([(14,20),(14,4),(17,2),(20,4),(20,22)],fill=1,width=2)
d.line([(20,21),(20,8),(23,6),(26,8),(26,25)],fill=1,width=2)
d.line([(26,20),(29,19),(31,21),(29,31),(25,37),(13,38),(6,33),(1,23),(2,20),(5,20),(9,27)],fill=1,width=2)
(ROOT/'rtl/ui23_hand.hex').write_text(''.join(f'{sum(im.getpixel((x,y))<< (31-x) for x in range(32)):08x}\n' for y in range(40)),encoding='ascii')
# A compact bold wordmark mask, only 3072 bits, independent of text spacing.
im=Image.new('1',(128,24));d=ImageDraw.Draw(im);logo_font=ImageFont.truetype(str(font_path),23)
b=d.textbbox((0,0),'TANGLAB',font=logo_font,stroke_width=1)
d.text((1-b[0],(24-(b[3]-b[1]))//2-b[1]),'TANGLAB',font=logo_font,fill=1,stroke_width=1)
(ROOT/'rtl/ui23_logo.hex').write_text(''.join(f'{sum(im.getpixel((x,y))<<(127-x) for x in range(128)):032x}\n' for y in range(24)),encoding='ascii')
# Same scan-line encoding as duo_fan: no trigonometry is synthesized.
spans=[]
for ns in profiles:
    for y in range(140):
        zones=[[] for _ in ns];hole=[]
        for x in range(280):
            dx=x-140;dy=140-y;r2=dx*dx+dy*dy
            if r2<80*80:hole.append(x)
            if r2<=138*138:
                a=math.atan2(dx,dy);z=min(len(ns)-1,max(0,int((a+math.pi/2)/math.pi*len(ns))))
                zones[z].append(x)
        word=0
        for z in range(12):
            xs=zones[z] if z<len(ns) else []
            lo,hi=(min(xs),max(xs)) if xs else (511,0)
            word|=lo<<(z*18);word|=hi<<(z*18+9)
        lo,hi=(min(hole),max(hole)) if hole else (511,0)
        word|=lo<<216;word|=hi<<225;spans.append(word)
(ROOT/'rtl/ui23_spans.hex').write_text(''.join(f'{v:059x}\n' for v in spans),encoding='ascii')
